const ts = require('typescript')
const fs = require('node:fs')
const assert = require('node:assert/strict')
require.extensions['.ts'] = (module, filename) => module._compile(ts.transpileModule(fs.readFileSync(filename, 'utf8'), {compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText, filename)
const {mapScanResponse} = require('../lib/scan-service.ts')
const {analyzeImage} = require('../lib/mock-engine.ts')
const payload = {inputType:'url',imageUrl:'/demo/sneaker.png',sourceUrl:'https://merchant.example/item',seed:'example-sneaker'}
const demo = analyzeImage({...payload,persona:'buyer'})
assert.equal(demo.demo,true)
assert.equal(demo.verdict,'high_risk')
assert.equal(demo.matches.filter(m=>m.whitelisted).length,2)
assert.equal(demo.matches.filter(m=>m.flagged).length,3)
assert.equal(analyzeImage({...payload,persona:'seller',seed:'example-insufficient'}).trustScore,null)
const raw = {id:'test',status:'completed',risk_category:'high_risk',trust_score:20,matched_domains:[{domain:'a.example',link:'javascript:alert(1)',extracted_price:NaN},{domain:'b.example',link:'https://b.example',extracted_price:200,currency:'INR'}]}
const mapped = mapScanResponse(raw,payload,'buyer')
assert.equal(mapped.matches[0].url,'')
assert.equal(mapped.matches[0].price,undefined)
assert.equal(mapped.confidence,'low')
assert.equal(mapped.verdict,'high_risk')
assert.equal(mapScanResponse({...raw,matched_domains:[]},payload,'buyer').trustScore,null)
assert.equal(mapScanResponse({...raw,status:'trusted_whitelist',matched_domains:[]},payload,'buyer').verdict,'trusted')
const stale = mapScanResponse({...raw,status:'stale_cached',risk_category:'moderate_risk',stale_original_timestamp:'2026-01-01T00:00:00Z'},payload,'seller')
assert.equal(stale.degraded,true)
assert.equal(stale.verdict,'moderate_risk')
assert.equal(stale.lastVerifiedAt,'2026-01-01T00:00:00Z')
assert.throws(()=>mapScanResponse({status:'failed'},payload,'buyer'))
console.log('PASS: deterministic demo, insufficient evidence, trusted bypass, stale cache, moderate risk, URL sanitation and optional fields')
